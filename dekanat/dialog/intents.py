"""Распознавание намерений и команд диалога правилами Python (регулярные выражения, словари).

Намерение «хочу перевестись / как поступить / нужно оформить заявление» требует желания или способа («хочу», «как», «нужно»):
вопросы о правилах («В какой срок принимается решение о переводе?») и о документе («Хватит ли справки для перевода?») анкету не запускают.
"""

from __future__ import annotations

import re
from typing import Optional

TRANSFER, ENROLLMENT, STATEMENT = "transfer", "enrollment", "statement"

_WISH = r"(?:хочу|хотел\w*|хотим|собираюсь|планирую|нужно|надо|нужен|нужна|можно\s+ли|могу\s+ли|как|помогите|подскажите|интересует)"

_TRANSFER = [
    re.compile(r"\bперевест(?:ись|ися)\b"),
    re.compile(rf"\b{_WISH}\b[^.?!]{{0,40}}\bперевод\w*\s+(?:в|к|из|на)\b(?!\s+русск)"),
    re.compile(r"\b(?:хочу|хотел\w*|собираюсь|планирую|можно\s+ли|могу\s+ли|как)\s+(?:мне\s+)?(?:\w+\s+){0,2}перейти\s+(?:в|к|на)\b"),
    re.compile(r"\bпереход\w*\s+(?:в|к)\s+(?:ваш|вас|вам)\b"),
    re.compile(r"\b(?:оформить|написать|подать|составить|заполнить|подготовить)\s+(?:мне\s+)?(?:\w+\s+){0,2}заявлени\w*\s+(?:о|на)\s+перевод\w*"),
]
_ENROLL = [
    re.compile(rf"\b{_WISH}\b[^.?!]{{0,30}}\bпоступ\w+"),
    re.compile(r"\bпоступить\s+(?:к\s+(?:вам|вас)|в\s+ваш)\b"),
    re.compile(rf"\b{_WISH}\b[^.?!]{{0,30}}\bзачисл\w+"),
    re.compile(r"\bзачислени\w*\s+(?:в|к)\s+(?:ваш|вас|вам)\b"),
    re.compile(r"\b(?:оформить|написать|подать|составить|заполнить|подготовить)\s+(?:мне\s+)?(?:\w+\s+){0,2}заявлени\w*\s+(?:о|на)\s+(?:зачислени\w*|поступлени\w*)"),
]
_STATEMENT = [
    re.compile(r"\b(?:оформить|написать|подать|составить|заполнить|сформировать|подготовить|создать)\s+(?:мне\s+)?(?:\w+\s+){0,2}заявлени\w+"),
    re.compile(r"\b(?:нужн\w+|надо)\s+(?:\w+\s+){0,2}заявлени\w+"),
]
_DOCUMENT_QUESTION = re.compile(r"\bпереводчик\w*|\bзаверенн\w+\s+перевод|\bперевод\w*\s+на\s+русск")
# «За сколько дней подать заявление?», «Когда подавать?», «Где подать?» — вопрос о правилах; без желания («хочу», «мне нужно») анкету не предлагаем
_RULE_QUESTION = re.compile(r"^(?:за\s+сколько|сколько|когда|до\s+какого|к\s+какому|в\s+какой\s+срок|в\s+какие\s+сроки|в\s+течение\s+скольки|где|куда)\b")
_PERSONAL_WISH = re.compile(r"\b(?:хочу|хотел\w*|хотим|собираюсь|планирую|мне\s+(?:нужно|надо)|помогите|помоги)\b")

# слова-«желания»: если правила ничего не нашли, а в сообщении есть желание, неоднозначную фразу можно отдать на разбор модели
_WISH_MARKERS = re.compile(r"хоч\w+|хотел\w*|нужн\w+|\bнадо\b|собира\w+|планир\w+|интерес\w+|помо\w+|подскаж\w+|\bкак\s+мне\b|\bможно\s+ли\b|\bможно\b")

# названия сценариев для текста предложения
SCENARIO_TITLES = {TRANSFER: "перевестись к нам", ENROLLMENT: "поступить к нам", STATEMENT: "оформить заявление"}


def _n(text: str) -> str:
    return re.sub(r"\s+", " ", str(text or "").lower().replace("ё", "е")).strip()


def detect_intent(text: str) -> Optional[str]:
    """transfer | enrollment | statement | None. Заявление на академический отпуск анкетой не покрывается."""
    n = _n(text)
    if not n or _DOCUMENT_QUESTION.search(n):
        return None
    if _RULE_QUESTION.search(n) and not _PERSONAL_WISH.search(n):
        return None
    if any(p.search(n) for p in _TRANSFER):
        return TRANSFER
    if any(p.search(n) for p in _ENROLL):
        return ENROLLMENT
    if any(p.search(n) for p in _STATEMENT):
        return None if "академ" in n else STATEMENT
    return None


def looks_ambiguous(text: str) -> bool:
    """Правила намерения не нашли, но человек явно о чём-то просит — такой фразе может помочь модель (если она включена)."""
    n = _n(text)
    return bool(_WISH_MARKERS.search(n)) and len(n.split()) >= 3


# ---------------------------------------------------------------- команды
_CMD = {
    "cancel": re.compile(r"^(?:отмена|отменить|отмена\s+анкеты|выйти|выход|прекратить|стоп|хватит|не\s+хочу\s+продолжать)\W*$"),
    "restart": re.compile(r"^(?:начать\s+(?:анкету\s+)?заново|давай\s+заново|заново|сначала|начать\s+сначала|перезапустить(?:\s+анкету)?|перезапуск)\W*$"),
    "back": re.compile(r"^(?:назад|вернуться|предыдущий(?:\s+вопрос)?)\W*$"),
    "skip": re.compile(r"^(?:пропустить|пропусти|пропуск|skip|пропустим|не\s+хочу\s+указывать|не\s+буду\s+указывать)\W*$"),
    "fix": re.compile(r"^(?:исправить|изменить|поправить|поменять|ошибся|ошиблась|не\s+так|неверно|неправильно|есть\s+ошибка)(?:\s+(?P<arg>.+?))?\W*$"),
    "confirm": re.compile(r"^(?:верно|все\s+верно|все\s+правильно|правильно|подтверждаю|подтвердить|да,?\s+верно|да|ок|окей|готово|согласен|согласна|все\s+ок)\W*$"),
    "yes": re.compile(r"^(?:да|да,?\s+(?:начать|давай\w*|хочу)|давай\w*|конечно|начать|начн\w+|хочу|ага|угу|погнали|можно|согласен|согласна|ок|окей|пожалуйста)\W*$"),
    "no": re.compile(r"^(?:нет|не\s+надо|не\s+нужно|не\s+сейчас|потом|не\s+хочу|позже|отказываюсь|отказ)\W*$"),
    "start": re.compile(r"^(?:начать\s+анкету|пройти\s+анкету|заполнить\s+анкету|анкета|начать)\W*$"),
    "generate": re.compile(r"^(?:сформировать|создать|сгенерировать)(?:\s+(?:документ|заявление))?\W*$"),
    # «Что ты умеешь?», «чем можешь помочь», «как пользоваться», «с чего начать» — целиком; фраза с продолжением («что ты можешь сказать про документ») — не помощь
    "help": re.compile(
        r"^(?:помощь|help|что\s+делать|\?"
        r"|что\s+(?:ты|вы)?\s*(?:умеешь|умеете|можешь|можете|умеет|может)(?:\s+(?:этот|данный))?(?:\s+(?:бот|секретарь|сервис|сайт|помощник|ассистент))?(?:\s+делать)?"
        r"|чем\s+(?:ты|вы)?\s*(?:можешь|можете|занимаешься|занимаетесь)(?:\s+(?:мне\s+)?помочь)?(?:\s+мне)?"
        r"|(?:как|с\s+чего)\s+(?:(?:тобой|этим|сервисом|сайтом|ботом)\s+)?(?:пользоваться|начать|работает|работать)"
        r"|как\s+это\s+работает|что\s+(?:здесь|тут)\s+(?:можно|делать)(?:\s+делать)?|возможности|кто\s+ты|что\s+это)\W*$"
    ),
    "resume": re.compile(r"^(?:продолжить|продолжим|продолжаем|где\s+я|повтор\w*(?:\s+вопрос)?)\W*$"),
}


def parse_command(text: str) -> Optional[tuple[str, str]]:
    """-> (имя команды, аргумент) либо None. Команда — это целое короткое сообщение, а не слово внутри ответа."""
    n = _n(text)
    if not n or len(n) > 80:
        return None
    for name, rx in _CMD.items():
        m = rx.match(n)
        if m:
            return name, (m.groupdict().get("arg") or "").strip()
    return None
